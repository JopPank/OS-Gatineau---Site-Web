-- Run this in the Supabase SQL editor after creating the project.
create table public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null,
    role text not null default 'athlete' check (role in ('athlete', 'coach', 'admin')),
    created_at timestamptz not null default now()
);

create table public.workouts (
    id bigint generated by default as identity primary key,
    athlete_id uuid not null references public.profiles(id) on delete cascade,
    title text not null,
    description text,
    file_url text,
    file_path text,
    created_at timestamptz not null default now()
);

insert into storage.buckets (id, name, public)
values ('workout-files', 'workout-files', false)
on conflict (id) do nothing;

alter table public.profiles enable row level security;
alter table public.workouts enable row level security;

create or replace function public.current_user_role()
returns text
language sql
security definer
set search_path = public
stable
as $$
    select role from public.profiles where id = auth.uid();
$$;

create policy "Athletes can read their own profile"
    on public.profiles for select
    using (auth.uid() = id);

create policy "Athletes can read their own workouts"
    on public.workouts for select
    using (auth.uid() = athlete_id);

create policy "Coaches and admins can read profiles"
    on public.profiles for select
    using (public.current_user_role() in ('coach', 'admin'));

create policy "Coaches and admins can manage workouts"
    on public.workouts for all
    using (public.current_user_role() in ('coach', 'admin'))
    with check (public.current_user_role() in ('coach', 'admin'));

create policy "Coaches and admins can upload workout files"
    on storage.objects for insert
    with check (
        bucket_id = 'workout-files'
        and public.current_user_role() in ('coach', 'admin')
    );

create policy "Users can read assigned workout files"
    on storage.objects for select
    using (
        bucket_id = 'workout-files'
        and (
            auth.uid()::text = split_part(name, '/', 1)
            or public.current_user_role() in ('coach', 'admin')
        )
    );
